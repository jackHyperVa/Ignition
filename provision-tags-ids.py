# Paste into Ignition Gateway Script Console and run.
# Gateway web UI -> Status -> Diagnostics -> Script Console
#
# Both the Ignition tag name and the OPC item path use sanitized names
# to match the simulator node IDs ([k]->[_k], space->_).
# One configure() call per device to stay under the RPC payload limit.
#
# Update OPC_CONNECTION to match your OPC-UA simulator connection name.

OPC_CONNECTION = "Simulator"

def opc_tag(tag_name, opc_node, data_type='Float8'):
    return {
        'name': tag_name, 'tagType': 'AtomicTag', 'valueSource': 'opc',
        'dataType': data_type, 'opcServer': OPC_CONNECTION,
        'opcItemPath': 'ns=1;s=' + opc_node, 'enabled': True,
    }

def folder(name, children):
    return {'name': name, 'tagType': 'Folder', 'tags': children}

def configure(path, tree):
    results = system.tag.configure(path, tree, 'o')
    ok  = sum(1 for r in results if r.good)
    bad = len(results) - ok
    print(path + ': ' + str(ok) + ' OK, ' + str(bad) + ' failed')
    if bad:
        for r in results:
            if not r.good: print('  FAIL:', r)

